/**
 * Renders BOARD.md from the loaded tickets.
 * @module tickets/board
 */
import { STATUSES, compareIds, readyTickets } from "./model.mjs";

/** @typedef {import("./model.mjs").Ticket} Ticket */

/** @type {Record<number, string>} */
const PHASE_NAMES = {
  0: "Foundation",
  1: "School core",
  2: "Console and production",
  3: "Self-serve and billing",
  4: "Themes and websites",
  5: "Custom domains",
  6: "Later",
};

/**
 * @param {number} phase
 * @returns {string} For example "Phase 0: Foundation".
 */
function phaseLabel(phase) {
  return `Phase ${phase}: ${PHASE_NAMES[phase] ?? "Unnamed"}`;
}

/**
 * Renders BOARD.md: ready tickets, work in flight, progress per phase, and every ticket.
 * @param {Ticket[]} tickets
 * @returns {string} Markdown text.
 */
export function renderBoard(tickets) {
  const sorted = [...tickets].sort((a, b) => compareIds(a.id, b.id));
  /** @param {Ticket} t */
  const link = (t) => `[${t.id}](${t.file})`;
  /** @param {string} value */
  const cell = (value) => value.replace(/\|/g, "\\|");
  const lines = [
    "# Ticket board",
    "",
    "Generated by `node tickets/tools/tickets.mjs board`. Do not edit by hand.",
    "",
    "## Ready to start",
    "",
  ];
  const ready = readyTickets(sorted);
  if (ready.length === 0) lines.push("Nothing is ready. Check the tickets in progress below.");
  for (const t of ready) lines.push(`- ${link(t)} ${t.title} (${t.type}, ${t.size})`);

  lines.push("", "## In progress, in review or blocked", "");
  const inFlight = sorted.filter((t) => ["doing", "review", "blocked"].includes(t.status));
  if (inFlight.length === 0) lines.push("None.");
  for (const t of inFlight) lines.push(`- ${link(t)} ${t.title}: **${t.status}**`);

  const phases = [...new Set(sorted.map((t) => t.phase))];
  lines.push("", "## Progress", "", "| Phase | Todo | Doing | Blocked | Review | Done | Total |", "|---|---|---|---|---|---|---|");
  for (const phase of phases) {
    const inPhase = sorted.filter((t) => t.phase === phase);
    const counts = STATUSES.map((status) => inPhase.filter((t) => t.status === status).length);
    lines.push(`| ${phaseLabel(phase)} | ${counts.join(" | ")} | ${inPhase.length} |`);
  }

  for (const phase of phases) {
    lines.push("", `## ${phaseLabel(phase)}`, "", "| ID | Title | Type | Size | Status | Depends on |", "|---|---|---|---|---|---|");
    for (const t of sorted.filter((x) => x.phase === phase)) {
      lines.push(`| ${link(t)} | ${cell(t.title)} | ${t.type} | ${t.size} | ${t.status} | ${t.dependsOn.join(", ") || "None"} |`);
    }
  }
  return `${lines.join("\n")}\n`;
}
